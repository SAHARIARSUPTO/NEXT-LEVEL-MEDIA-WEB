<!-- Scroll-Driven Vertical Success Line Script -->
<script>
  (function initVerticalStepsProgress() {
    const container = document.getElementById('stepsTimelineContainer');
    const progressBar = document.getElementById('stepsProgressBar');
    const milestones = document.querySelectorAll('.step-milestone');

    if (!container || !progressBar || !milestones.length) return;

    function updateStepsProgress() {
      const rect = container.getBoundingClientRect();
      const windowHeight = window.innerHeight;

      // Trigger line when container enters middle of screen
      const startOffset = windowHeight * 0.75;
      const totalScrollDistance = rect.height;
      const currentScroll = startOffset - rect.top;

      let progress = currentScroll / totalScrollDistance;
      progress = Math.max(0, Math.min(progress, 1));

      // Update vertical progress line height in pixels
      const fillHeight = progress * rect.height;
      progressBar.style.height = `${fillHeight}px`;

      // Check each milestone
      milestones.forEach((item) => {
        const itemRect = item.getBoundingClientRect();
        const point = item.querySelector('.step-node-point');
        const num = item.querySelector('.step-node-number');
        const check = item.querySelector('.step-node-check');
        const card = item.querySelector('.step-card');

        // Node is reached when the line passes its top offset
        const nodePassed = (rect.top + fillHeight) >= (itemRect.top + 30);

        if (nodePassed) {
          point.classList.add('bg-gradient-to-br', 'from-blue-500', 'to-violet-600', 'text-white', 'border-white', 'scale-110', 'shadow-[0_0_30px_rgba(139,92,246,0.8)]');
          point.classList.remove('bg-[#09090d]', 'border-white/25', 'text-gray-400');
          if (num) num.classList.add('hidden');
          if (check) check.classList.remove('hidden');
          if (card) {
            card.classList.add('border-violet-500/60', 'shadow-[0_20px_50px_rgba(139,92,246,0.2)]');
          }
        } else {
          point.classList.remove('bg-gradient-to-br', 'from-blue-500', 'to-violet-600', 'text-white', 'border-white', 'scale-110', 'shadow-[0_0_30px_rgba(139,92,246,0.8)]');
          point.classList.add('bg-[#09090d]', 'border-white/25', 'text-gray-400');
          if (num) num.classList.remove('hidden');
          if (check) check.classList.add('hidden');
          if (card) {
            card.classList.remove('border-violet-500/60', 'shadow-[0_20px_50px_rgba(139,92,246,0.2)]');
          }
        }
      });
    }

    window.addEventListener('scroll', updateStepsProgress, { passive: true });
    window.addEventListener('resize', updateStepsProgress, { passive: true });
    if (typeof lenis !== 'undefined') {
      lenis.on('scroll', updateStepsProgress);
    }
    updateStepsProgress();
  })();
</script>