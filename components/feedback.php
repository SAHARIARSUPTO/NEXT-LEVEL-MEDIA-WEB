<!-- Mobile Card Stacking Interactive Scroll Controller -->
<script>
  (function initMobileBenefitCardStacking() {
    const cards = document.querySelectorAll('.benefit-stack-card');
    if (!cards.length) return;

    let isThrottled = false;

    function handleCardStack() {
      if (window.innerWidth >= 768) {
        cards.forEach(card => {
          card.style.transform = '';
          card.style.filter = '';
        });
        return;
      }
      
      cards.forEach((card, index) => {
        const rect = card.getBoundingClientRect();
        const stickyTop = 80 + index * 16;
        if (rect.top <= stickyTop + 10) {
          const nextCard = cards[index + 1];
          if (nextCard) {
            const nextRect = nextCard.getBoundingClientRect();
            const overlap = Math.max(0, (stickyTop + rect.height) - nextRect.top);
            const progress = Math.min(overlap / (rect.height * 0.8), 1);
            const scale = 1 - progress * 0.04;
            const brightness = 1 - progress * 0.25;
            card.style.transform = `scale(${scale})`;
            card.style.filter = `brightness(${brightness})`;
          }
        } else {
          card.style.transform = 'scale(1)';
          card.style.filter = 'brightness(1)';
        }
      });
    }

    function onScrollThrottled() {
      if (!isThrottled) {
        requestAnimationFrame(() => {
          handleCardStack();
          isThrottled = false;
        });
        isThrottled = true;
      }
    }

    window.addEventListener('scroll', onScrollThrottled, { passive: true });
    window.addEventListener('resize', onScrollThrottled, { passive: true });
    if (typeof lenis !== 'undefined') lenis.on('scroll', onScrollThrottled);
  })();
</script>
